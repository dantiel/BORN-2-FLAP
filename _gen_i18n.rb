#!/usr/bin/env ruby
# frozen_string_literal: true

# gen_i18n_header — emit Unreal/Born2Flap/Source/Born2Flap/UI/Born2FlapI18n.h
# from the canonical locale dictionaries (Brain/lib/born2flap/i18n/locales/*.json).
#
# The JSON is the single authority for game strings; this script keeps the C++
# renderer in lock-step so the Ruby Brain, the native renderer and the website
# never drift apart. Regenerate after editing any locale file:
#
#   Brain/bin/gen_i18n_header

require "json"
require "fileutils"

ROOT = File.expand_path("../..", __dir__)
LOCALES_DIR = File.join(ROOT, "Brain/lib/born2flap/i18n/locales")
OUT = File.join(ROOT, "Unreal/Born2Flap/Source/Born2Flap/UI/Born2FlapI18n.h")

def load(lang)
  JSON.parse(File.read(File.join(LOCALES_DIR, "#{lang}.json"), encoding: "UTF-8"))
end

# C++ string-literal escaping for a UTF-8 value.
def cpp_str(value)
  value.to_s
       .gsub("\\", "\\\\")
       .gsub('"', '\\"')
end

def table(lang, dict)
  lines = dict.map do |key, value|
    %(        { "#{cpp_str(key)}", "#{cpp_str(value)}" },)
  end
  <<~TABLE.chomp
    static const Entry #{lang.capitalize}[] =
    {
    #{lines.join("\n")}
    };
  TABLE
end

langs = Dir[File.join(LOCALES_DIR, "*.json")]
          .map { |f| File.basename(f, ".json") }
          .sort
langs.delete("en")
langs.unshift("en") # English first, then alphabetical — reproducible output

en = load("en")
dicts = langs.to_h { |lang| [lang, load(lang)] }

dispatch = langs.reject { |l| l == "en" }.map do |lang|
  %(    if (Code == TEXT("#{lang}")) return #{lang.capitalize};)
end.join("\n")

header = <<~HEADER
  // Born2FlapI18n.h — generated by Brain/bin/gen_i18n_header from
  // Brain/lib/born2flap/i18n/locales/*.json. Do not edit by hand; edit the JSON
  // and regenerate. The JSON is the single authority for game strings, shared by
  // the Ruby Brain, this native renderer and the website.
  //
  // Semantic-key string lookup with per-locale fallback to English:
  //
  //   Born2Flap::I18n::SetLocale(TEXT("de"));
  //   FString Alt = Born2Flap::I18n::T("hud.altitude");  // => "HÖHE"

  #pragma once

  #include "CoreMinimal.h"
  #include "Containers/StringConv.h"
  #include "Containers/ArrayView.h"

  #include <string.h>

  namespace Born2Flap::I18n
  {
      struct Entry { const char* Key; const char* Value; };

      // Active locale code ("en", "de", ...). Unknown codes fall back to English.
      inline FString& ActiveLocale()
      {
          static FString L = TEXT("en");
          return L;
      }

      inline void SetLocale(const FString& Code)
      {
          ActiveLocale() = Code.IsEmpty() ? FString(TEXT("en")) : Code;
      }

      inline void SetLocale(const char* Code)
      {
          if (Code == nullptr || *Code == '\\0')
              ActiveLocale() = TEXT("en");
          else
              ActiveLocale() = FString(UTF8_TO_TCHAR(Code));
      }

      inline FString GetLocale() { return ActiveLocale(); }

      inline TArrayView<const Entry> TableFor(const FString& Code)
      {
  #{table("en", en)}

  #{langs.reject { |l| l == "en" }.map { |l| table(l, dicts[l]) }.join("\n\n")}

  #{dispatch}
          return En; // unknown → English
      }

      inline const char* Lookup8(const char* Key)
      {
          for (const Entry& E : TableFor(ActiveLocale()))
              if (strcmp(E.Key, Key) == 0)
                  return E.Value;
          for (const Entry& E : TableFor(FString(TEXT("en"))))
              if (strcmp(E.Key, Key) == 0)
                  return E.Value;
          return Key; // last resort: surface the key itself
      }

      // Translate a semantic key ("hud.altitude") in the active locale.
      inline FString T(const char* Key)
      {
          return FString(UTF8_TO_TCHAR(Lookup8(Key)));
      }

      inline FString T(const FString& Key)
      {
          return T(TCHAR_TO_UTF8(*Key));
      }
  }
HEADER

File.write(OUT, header + "\n")
puts "wrote #{OUT} (#{langs.size} locales, #{en.size} keys)"